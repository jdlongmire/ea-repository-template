#!/usr/bin/env python3
"""Render the registered views from the catalog.

Usage:
    python3 00-meta-model/render_views.py [--check]

Reads 00-meta-model/catalog.toml (the model of record) and
00-meta-model/views.toml (the view register) and generates, for each
registered view, two outputs in 05-evidence/views/:

  <view-id>.mmd   Mermaid source: the editable, diffable drawing.
  <view-id>.svg   A rendered SVG: the evidence form of the same view.

Both are generated, never hand-edited. The verifier (verify.py)
regenerates them in memory and fails if the committed files differ,
so a drawing that disagrees with the catalog cannot survive CI.
Standard library only.
"""
import sys
import tomllib
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "05-evidence" / "views"
LEVEL_ORDER = ["enterprise", "systems", "solutions", "cross-cutting", "cross-level"]


def load_catalog(root=ROOT):
    with open(root / "00-meta-model" / "catalog.toml", "rb") as fh:
        return tomllib.load(fh)


def load_views(root=ROOT):
    with open(root / "00-meta-model" / "views.toml", "rb") as fh:
        return tomllib.load(fh)


def view_edges(view, relations):
    """Relations a view draws: every catalogued relation between two
    shown elements, or exactly the view's declared subset."""
    shown = set(view["elements"])
    edges = [
        (r["source"], r["relation"], r["target"])
        for r in relations
        if r["source"] in shown and r["target"] in shown
    ]
    declared = view.get("relations")
    if declared is not None:
        wanted = set()
        for item in declared:
            source, verb, target = item.split(" ")
            wanted.add((source, verb, target))
        edges = [e for e in edges if e in wanted]
    return sorted(edges)


def node_key(element_id):
    return element_id.replace("-", "_")


def build_mermaid(view, elements, edges):
    by_id = {e["id"]: e for e in elements}
    lines = [
        f"%% {view['id']} {view['title']} ({view['level']}, {view['focus']})",
        "%% Generated by 00-meta-model/render_views.py from catalog.toml and views.toml. Do not edit.",
        "flowchart TD",
    ]
    for eid in sorted(view["elements"]):
        label = f"{eid}: {by_id[eid]['name']}"
        lines.append(f'    {node_key(eid)}["{label}"]')
    for source, verb, target in edges:
        lines.append(f"    {node_key(source)} -->|{verb}| {node_key(target)}")
    return "\n".join(lines) + "\n"


def build_svg(view, elements, edges):
    by_id = {e["id"]: e for e in elements}
    bands = {}
    for eid in view["elements"]:
        bands.setdefault(by_id[eid]["level"], []).append(eid)
    ordered_bands = sorted(bands, key=lambda lv: LEVEL_ORDER.index(lv) if lv in LEVEL_ORDER else 99)
    box_w, box_h, gap_x, band_h, margin = 216, 46, 24, 116, 20
    cols = max(len(bands[lv]) for lv in ordered_bands)
    width = margin * 2 + cols * box_w + (cols - 1) * gap_x
    height = margin * 2 + len(ordered_bands) * band_h
    pos = {}
    for row, lv in enumerate(ordered_bands):
        for col, eid in enumerate(sorted(bands[lv])):
            x = margin + col * (box_w + gap_x)
            y = margin + row * band_h + 18
            pos[eid] = (x, y)
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        f"<title>{escape(view['id'])} {escape(view['title'])}</title>",
        '<rect width="100%" height="100%" fill="#ffffff"/>',
    ]
    for row, lv in enumerate(ordered_bands):
        y = margin + row * band_h
        out.append(f'<text x="{margin}" y="{y + 12}" font-family="sans-serif" font-size="11" fill="#666666">{escape(lv)}</text>')
    for source, verb, target in edges:
        sx, sy = pos[source]
        tx, ty = pos[target]
        x1, y1 = sx + box_w / 2, sy + box_h / 2
        x2, y2 = tx + box_w / 2, ty + box_h / 2
        out.append(f'<line x1="{x1:.0f}" y1="{y1:.0f}" x2="{x2:.0f}" y2="{y2:.0f}" stroke="#888888" stroke-width="1.2"/>')
        out.append(
            f'<text x="{(x1 + x2) / 2:.0f}" y="{(y1 + y2) / 2:.0f}" font-family="sans-serif" '
            f'font-size="10" fill="#555555" text-anchor="middle">{escape(verb)}</text>'
        )
    for eid in sorted(view["elements"]):
        x, y = pos[eid]
        name = by_id[eid]["name"]
        out.append(f'<rect x="{x}" y="{y}" width="{box_w}" height="{box_h}" rx="6" fill="#eef1f8" stroke="#1e2456"/>')
        out.append(
            f'<text x="{x + box_w / 2}" y="{y + 20}" font-family="sans-serif" font-size="12" '
            f'font-weight="bold" fill="#1e2456" text-anchor="middle">{escape(eid)}</text>'
        )
        out.append(
            f'<text x="{x + box_w / 2}" y="{y + 36}" font-family="sans-serif" font-size="10" '
            f'fill="#333333" text-anchor="middle">{escape(name[:34])}</text>'
        )
    out.append("</svg>")
    return "\n".join(out) + "\n"


def expected_files(root=ROOT):
    catalog = load_catalog(root)
    register = load_views(root)
    files = {}
    for view in register.get("view", []):
        edges = view_edges(view, catalog.get("relation", []))
        stem = view["id"].lower()
        files[f"05-evidence/views/{stem}.mmd"] = build_mermaid(view, catalog["element"], edges)
        files[f"05-evidence/views/{stem}.svg"] = build_svg(view, catalog["element"], edges)
    return files


def main():
    files = expected_files()
    if "--check" in sys.argv:
        stale = [p for p, content in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != content]
        if stale:
            print("STALE view outputs:", *stale, sep="\n - ")
            sys.exit(1)
        print(f"OK: {len(files)} generated view outputs are current.")
        return
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for rel, content in files.items():
        (ROOT / rel).write_text(content)
    print(f"wrote {len(files)} view outputs to 05-evidence/views/")


if __name__ == "__main__":
    main()
